LOCKED = {"r3context": "0.6.10", "Charset_Normalizer": "3.5.1", "soupsieve": "3.0.4"}


def app_packages(
    tmp_path: Path, versions: dict[str, str], generator: str = "uv 0.9.30"
) -> Path:
    """An app_packages folder that holds each distribution at its version, each built
    by ``generator``."""
    packages = tmp_path / "app_packages"
    for name, version in versions.items():
        dist_info = packages / f"{name}-{version}.dist-info"
        dist_info.mkdir(parents=True)
        metadata = f"Metadata-Version: 2.1\nName: {name}\nVersion: {version}\n"
        (dist_info / "METADATA").write_text(metadata, encoding="utf-8")
        wheel = f"Wheel-Version: 1.0\nGenerator: {generator}\n"
        (dist_info / "WHEEL").write_text(wheel, encoding="utf-8")
    return packages


